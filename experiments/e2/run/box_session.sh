#!/bin/bash
# E2 pilot — the box session, steps 1 through threshold freeze, gated.
#
# Run this ON THE AUTHORIZED 24 GB BOX from the repo root:
#   bash experiments/e2/run/box_session.sh
#
# It stops at every gate that is not satisfied and tells you exactly what
# only you can do (HF login; the license sentences). It ends at
# e2_config.json and refuses to go further: the evaluation half and the
# harmful set are not scored today (owner rule: never the same day as
# calibration). Rerunning after fixing a gate is safe — every step is
# idempotent or refuses cleanly.
set -euo pipefail
cd "$(git rev-parse --show-toplevel)"
RUN=experiments/e2/run
SCRATCH="${E2_SCRATCH:-$HOME/e2-scratch}"
mkdir -p "$SCRATCH"

step() { printf '\n=== %s ===\n' "$*"; }

step "Gate 0 — the machine itself"
MEM=$(sysctl -n hw.memsize)
if [ "$MEM" -lt 25769803776 ]; then
  echo "hw.memsize $(($MEM / 1073741824)) GiB < 24 GiB — NOT the authorized box. Stop."
  exit 1
fi
FREE_GB=$(df -g . | awk 'NR==2 {print $4}')
if [ "$FREE_GB" -lt 60 ]; then
  echo "only ${FREE_GB}G free — the three pinned downloads plus an 8-bit"
  echo "LG4 conversion need ~60G headroom. Clear space first. Stop."
  exit 1
fi
echo "ok    $(($MEM / 1073741824)) GiB unified, ${FREE_GB}G free"

step "Step 1 — freeze holds"
python3 experiments/e2/freeze/check_freeze.py

step "Step 2 — environment (from the committed lockfile)"
if [ ! -d "$SCRATCH/venv" ]; then python3 -m venv "$SCRATCH/venv"; fi
"$SCRATCH/venv/bin/pip" install -q -r "$RUN/env-probe.freeze.txt"
"$SCRATCH/venv/bin/python" - <<'PY'
import torch, transformers, mlx_lm
assert torch.backends.mps.is_available(), "MPS not available on this box"
print(f"ok    torch {torch.__version__} (MPS), transformers "
      f"{transformers.__version__}, mlx_lm {mlx_lm.__version__}")
PY
PYV="$SCRATCH/venv/bin/python"

step "Step 3a — Hugging Face login (your account, your hands)"
if ! "$SCRATCH/venv/bin/huggingface-cli" whoami >/dev/null 2>&1; then
  echo "Not logged in. Run:  $SCRATCH/venv/bin/huggingface-cli login"
  echo "(the token stays in your user account; it never enters the repo)"
  echo "Then rerun this script. Stop."
  exit 1
fi
echo "ok    authenticated as $("$SCRATCH/venv/bin/huggingface-cli" whoami | head -1)"

step "Step 3b — pinned downloads (revisions from the freeze, never main)"
DL="$SCRATCH/models"
"$SCRATCH/venv/bin/huggingface-cli" download meta-llama/Llama-Guard-4-12B \
  --revision 87acb4b94e930c3d679e6e7ee9d57e2feab9ea71 --local-dir "$DL/lg4"
"$SCRATCH/venv/bin/huggingface-cli" download meta-llama/Llama-Guard-3-8B \
  --revision 7327bd9f6efbbe6101dc6cc4736302b3cbb6e425 --local-dir "$DL/lg3"
"$SCRATCH/venv/bin/huggingface-cli" download google/shieldgemma-2b \
  --revision d1dffc9c8c9237a90aab09c61383791e718ef9e8 --local-dir "$DL/sg2b"

step "Step 3c — license record (your sentences, not mine)"
echo "LICENSE-like files found, with sha256 (paste into LICENSES.md):"
find "$DL" -maxdepth 2 -iname "LICENSE*" -o -iname "*license*" -maxdepth 2 \
  | while read -r f; do shasum -a 256 "$f"; done || true
if [ ! -f "$RUN/LICENSES.md" ]; then
  echo ""
  echo "Create $RUN/LICENSES.md from LICENSES.template.md: gate-accept"
  echo "dates, the hashes above, and your three commercial_reuse"
  echo "sentences. Then rerun. Stop."
  exit 1
fi
python3 "$RUN/check_box.py"   # validates the record's shape, memory again

step "Step 4 — LG4 8-bit local conversion (LG4_CONFIG.md)"
if [ ! -d "$SCRATCH/lg4-8bit" ]; then
  "$PYV" -m mlx_lm.convert --hf-path "$DL/lg4" \
    --mlx-path "$SCRATCH/lg4-8bit" -q --q-bits 8
fi
if [ ! -f "$RUN/LG4_CONVERSION.md" ]; then
  { echo "# LG4 8-bit conversion record — generated by box_session.sh"
    date -u +"Converted: %Y-%m-%dT%H:%M:%SZ"
    echo "Tool: mlx_lm.convert ($("$PYV" -c 'import mlx_lm; print(mlx_lm.__version__)')) , -q --q-bits 8"
    echo "Source: local pinned snapshot of meta-llama/Llama-Guard-4-12B @ 87acb4b9"
    echo "Output hashes:"
    find "$SCRATCH/lg4-8bit" -type f -name "*.safetensors" -exec shasum -a 256 {} \;
  } > "$RUN/LG4_CONVERSION.md"
  echo "ok    LG4_CONVERSION.md written — commit it with your session"
fi
export E2_LG4_MODEL_PATH="$SCRATCH/lg4-8bit"

step "Step 5 — shakeout (synthetic + one throwaway string per guard)"
export E2_ON_AUTHORIZED_BOX=1
python3 "$RUN/calibrate.py" --synthetic --out "$SCRATCH/shakeout"
"$PYV" - <<'PY'
import os, sys
sys.path.insert(0, "experiments/e2/run")
from adapters import SCORERS
for g, fn in SCORERS.items():
    s = fn("This is a declared throwaway shakeout string, not a frozen item.")
    assert 0.0 <= s <= 1.0, (g, s)
    print(f"ok    {g} adapter forward pass on throwaway string: score {s:.4f}")
PY

step "Step 6 — the real calibration tokens (calibration half ONLY)"
"$PYV" "$RUN/calibrate.py" --guard sg2b --out "$SCRATCH/cal"
"$PYV" "$RUN/calibrate.py" --guard lg3  --out "$SCRATCH/cal"
"$PYV" "$RUN/calibrate.py" --guard lg4  --out "$SCRATCH/cal"

step "Step 7 — threshold freeze"
python3 "$RUN/make_config.py" --indir "$SCRATCH/cal"
echo ""
echo "Copy $SCRATCH/cal/e2_config.json somewhere durable, commit"
echo "LG4_CONVERSION.md and LICENSES.md, and stop for today."
