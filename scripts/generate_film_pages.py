    assert video_node(changed)['uploadDate'] == pub['first_site_publication']
    broken = copy.deepcopy(r); broken['determinism']['identical'] = False
    try:
        validate_record(m, broken, pub)
    except ValueError:
        pass
    else:
        raise AssertionError('accepted nondeterministic render')
    for film in films:
        node = video_node(film)
        assert set(['name', 'description', 'thumbnailUrl', 'uploadDate', 'contentUrl', 'duration']) <= node.keys()
        assert 'license' not in node and 'interactionStatistic' not in node
    print('ok    film metadata: failed deployments, wrong paths, undated publication and failed renders refuse; render date cannot become upload date')
    curation = load_curation({f['manifest']['id'] for f in films})
    test_editorial_surfaces(films, curation)
    print('ok    film curriculum: six ordered primary questions, all alternate URLs, real post-player proof links, retained film-specific CTAs, concise limits and original technical wording')
    # a receipt binds the values of the facts it read: no other fact can stale it, and every one of those can
    facts = json.loads((ROOT / facts_digest.FILE).read_text())['facts']
    reads = 0
    for film in load_films(facts):
        r = film['receipt']
        for fid in facts:
            changed = {**facts, fid: {**facts[fid], 'value': ['mutated', facts[fid]['value']]}}
            if (facts_digest.stale(r, changed) is None) != (fid not in r['facts_used']):
                raise AssertionError(f"{r['film']}: changing {fid} {'staled' if fid not in r['facts_used'] else 'did not stale'} the render")
            reads += fid in r['facts_used']
        for fid in r['facts_used']:
            if not facts_digest.stale(r, {k: v for k, v in facts.items() if k != fid}):
                raise AssertionError(f"{r['film']}: removing {fid} did not stale the render")
