def sha(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def route(slug: str) -> str:
    return f'/films/{slug}/'


def public_path(rel: str) -> str:
    return f'{SITE}/{rel}'


def load_curation(slugs: set[str]) -> dict:
    """Keep watch order and readable summaries separate from frozen film evidence."""
    data = json.loads((ROOT / 'films/curation.json').read_text())
    validate_curation(data, slugs)
    return data


def validate_curation(data: dict, slugs: set[str]) -> None:
    primary = data['primary']
    alternates = data['alternates']
    if len(primary) != 6 or len(set(primary)) != 6:
        raise ValueError('film curriculum requires six distinct primary questions')
    if primary[0] != 'same-scores-different-worlds':
        raise ValueError('introductory construction must be first')
    if not set(alternates) <= set(primary):
        raise ValueError('alternate cuts must be nested under a primary film')
    listed = primary + [slug for group in alternates.values() for slug in group]
    if len(listed) != len(set(listed)) or set(listed) != slugs or set(data['films']) != slugs:
        raise ValueError('curation must include every film exactly once')
    for slug, item in data['films'].items():
        if not item.get('synopsis', '').strip() or not 1 <= len(item['limits']) <= 4:
            raise ValueError(f'{slug}: synopsis and one to four consolidated limits required')
        if len(set(item['limits'])) != len(item['limits']) or any(not n.strip() for n in item['limits']):
            raise ValueError(f'{slug}: empty or duplicated consolidated limit')


def validate_render_assets(path: Path, manifest: dict, receipt: dict, fmt: str, facts: dict) -> dict:
    slug = manifest['id']
    if receipt['film'] != slug or receipt['format'] != fmt:
        raise ValueError(f'{slug}: wrong {fmt} render receipt')
    if not receipt['determinism']['identical'] or receipt['text_overflows']:
        raise ValueError(f'{slug}: {fmt} render did not pass determinism/overflow checks')
    if abs(float(receipt['duration_s']) - float(manifest['duration_s'])) > 1 / receipt['fps']:
        raise ValueError(f'{slug}: {fmt} duration differs from the declared film')
    if receipt['outputs']['master'] != f'renders/{slug}__{fmt}.mp4':
        raise ValueError(f'{slug}: {fmt} render output points at another file')
    if fmt in ('vertical', 'square'):
        validate_phone_text(receipt)
    for rel, digest in receipt['inputs'].items():
        source = path.parent / rel if rel == 'film.html' else ROOT / rel
        if sha(source) != digest:
            raise ValueError(f'{slug}: {fmt} render input is stale: {rel}')
    why = facts_digest.stale(receipt, facts)
    if why:
        raise ValueError(f'{slug}: {fmt} render is stale: {why}')
    video = path.parent / receipt['outputs']['master']
    if sha(video) != receipt['outputs']['master_sha256']:
        raise ValueError(f'{slug}: {fmt} video bytes differ from render receipt')
    poster = path.parent / receipt['outputs']['poster']
    if not poster.is_file():
        raise ValueError(f'{slug}: {fmt} poster missing')
    return {'receipt': receipt, 'video': video.relative_to(ROOT).as_posix(),
            'poster': poster.relative_to(ROOT).as_posix()}


def validate_phone_text(receipt: dict) -> None:
    """Check measured font geometry; this is not reader comprehension evidence."""
    audit = receipt.get('phone_text') or {}
    minimum = audit.get('minimum_canvas_px')
    css = audit.get('minimum_css_px')
    if (type(minimum) not in (int, float) or not math.isfinite(minimum)
            or type(css) not in (int, float) or not math.isfinite(css)
            or type(audit.get('audited_draws')) is not int or audit['audited_draws'] <= 0
            or audit.get('media_width_css_px') != 280
            or abs(css - minimum * 280 / receipt['width']) > 1e-6
            or css < 14 - 1e-6):
        raise ValueError(f"{receipt['film']}: missing or undersized phone text audit")


def validate_record(manifest: dict, receipt: dict, publication: dict) -> None:
    slug = manifest['id']
    fmt = manifest.get('render', {}).get('primary', 'master')
    expected = f'films/{slug}/renders/{slug}__{fmt}.mp4'
    if receipt['film'] != slug or receipt['format'] != fmt:
        raise ValueError(f'{slug}: wrong render receipt')
    if publication['film'] != slug or publication['video_path'] != expected:
        raise ValueError(f'{slug}: publication record names a different video')
    if publication['primary_format'] != fmt or publication['status'] != 'success':
        raise ValueError(f'{slug}: no successful primary-video publication')
    if publication['environment_url'] != SITE + '/':
        raise ValueError(f'{slug}: publication belongs to another site')
    date = dt.datetime.fromisoformat(publication['first_site_publication'].replace('Z', '+00:00'))
    if date.tzinfo is None:
        raise ValueError(f'{slug}: publication timestamp has no timezone')
    expected_source = f"https://api.github.com/repos/Cubits11/cubits11.github.io/deployments/{publication['deployment_id']}/statuses"
    if publication['source_url'] != expected_source:
        raise ValueError(f'{slug}: deployment source differs')
    if not receipt['determinism']['identical'] or receipt['text_overflows']:
        raise ValueError(f'{slug}: render did not pass determinism/overflow checks')
    if abs(float(receipt['duration_s']) - float(manifest['duration_s'])) > 1 / receipt['fps']:
        raise ValueError(f'{slug}: duration differs from the declared film')
    if receipt['outputs']['master'] != f'renders/{slug}__{fmt}.mp4':
        raise ValueError(f'{slug}: render output points at another file')


def load_films(facts: dict | None = None) -> list[dict]:
    if facts is None:
        facts = json.loads((ROOT / facts_digest.FILE).read_text())['facts']
    history = json.loads((ROOT / 'films/publication-history.json').read_text())
    pubs = {p['film']: p for p in history['films']}
    if len(pubs) != len(history['films']):
        raise ValueError('duplicate film publication record')
    films = []
    for path in sorted((ROOT / 'films').glob('*/manifest.yaml')):
        m = yaml.safe_load(path.read_text())
        slug = path.parent.name
        if slug != m['id']:
            raise ValueError(f'{slug}: mismatched manifest id')
        fmt = m.get('render', {}).get('primary', 'master')
        receipt_path = path.parent / f'renders/{slug}__{fmt}.receipt.json'
        r = json.loads(receipt_path.read_text())
        publication = pubs[slug]
        validate_record(m, r, publication)
        assets = validate_render_assets(path, m, r, fmt, facts)
        phone = None
        if fmt != 'vertical' and 'vertical' in m.get('render', {}).get('formats', []):
            phone_receipt = json.loads((path.parent / f'renders/{slug}__vertical.receipt.json').read_text())
            phone = validate_render_assets(path, m, phone_receipt, 'vertical', facts)
        films.append({'manifest': m, 'receipt': r, 'publication': publication,
                      'video': assets['video'], 'poster': assets['poster'], 'phone': phone,
                      'receipt_path': receipt_path.relative_to(ROOT).as_posix()})
    if set(pubs) != {f['manifest']['id'] for f in films}:
        raise ValueError('publication inventory differs from film manifests')
    return films


