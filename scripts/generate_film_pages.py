def render_index(films: list[dict], curation: dict) -> str:
    title = 'Films — safety scores, hidden overlap and checkable claims'
    by_slug = {f['manifest']['id']: f for f in films}
    primary = [by_slug[slug] for slug in curation['primary']]
    desc = 'Six questions about guardrail composition and evidence, with alternate cuts grouped beneath their primary argument. Start with identical scores and different shared failures.'
    node = {'@context': 'https://schema.org', '@type': 'CollectionPage', 'name': title,
            'description': desc, 'url': SITE + '/films/', 'mainEntity': {'@type': 'ItemList',
                'numberOfItems': len(primary), 'itemListElement': [
                    {'@type': 'ListItem', 'position': i, 'name': f['manifest']['title'], 'url': SITE + route(f['manifest']['id'])}
                    for i, f in enumerate(primary, 1)]}}
    cards = []
    for f in primary:
        slug = f['manifest']['id']
        item = curation['films'][slug]
        alternatives = curation['alternates'].get(slug, [])
        extra = ''
        if alternatives:
            links = ' · '.join(f'<a class="u" href="{route(alt)}">{esc(by_slug[alt]["manifest"]["title"])}</a>' for alt in alternatives)
            label = 'Other cuts of this construction' if slug == 'same-scores-different-worlds' else 'Trailer and correction record'
            extra = f'<p class="film-alternates">{label}:<br>{links}</p>'
        cards.append(f'''<li><a class="film-card" href="{route(slug)}">
<img src="/{f['poster']}" width="{f['receipt']['width']}" height="{f['receipt']['height']}" loading="lazy" alt="">
<div><h2>{esc(item.get('heading', f['manifest']['title']))}</h2><p>{esc(item['synopsis'])}</p><p>{f['manifest']['duration_s']:g} seconds · silent · text argument and sources</p></div></a>{extra}</li>''')
    return (BANNER + head(title, desc, '/films/', 'website', [node]).replace('</head>', STYLE + '</head>') + SITE_HEAD + f'''
<header class="page"><div class="container"><p class="eyebrow mono">Watch · inspect · challenge</p>
<h1 class="q">What the scores leave out</h1><p class="standfirst">Start with the constructed example, then inspect released data, higher-order overlap, public reporting, and receipt limits. Six distinct questions; alternate cuts and correction history stay with their primary argument.</p></div></header>
<main class="container" id="main"><ul class="film-grid">{''.join(cards)}</ul></main>
''' + footer([('/limits/', 'What checks establish'), ('/claims/', 'Claim registry'), ('/missing-column/', 'The Missing Column'), ('/corrections/', 'Corrections')]))


