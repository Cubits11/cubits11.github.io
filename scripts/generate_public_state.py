#!/usr/bin/env python3
"""Render public review dates and draft locations without changing claim status.

Claim due dates come from claims.yaml. Other public promises come from
publications.yaml. Runtime date updates keep an elapsed deadline visible even
when the scientific release gate prevents publishing a new site build.
"""
from __future__ import annotations

import datetime as dt
import json
from pathlib import Path
import subprocess
import sys
from functools import lru_cache
import yaml

from generate_claims_pages import head, footer, SITE_HEAD, esc

ROOT = Path(__file__).resolve().parent.parent
BANNER = '<!doctype html>\n<!-- GENERATED by scripts/generate_public_state.py; do not hand-edit. -->\n'


def date(value):
    return dt.date.fromisoformat(str(value))


@lru_cache(maxsize=None)
def registry_at(revision):
    if len(revision) != 40 or any(c not in '0123456789abcdef' for c in revision):
        raise ValueError('invalid registry revision')
    content = subprocess.check_output(['git', 'show', revision + ':claims.yaml'], cwd=ROOT, text=True)
    return {claim['id']: claim for claim in yaml.safe_load(content)['claims']}


def records(claims, publications):
    result = []
    for claim in claims['claims']:
        due = date(claim['last_reviewed']) + dt.timedelta(days=int(claim['review_window_days']))
        result.append({'id': claim['id'], 'title': claim['id'] + ' evidence review',
                       'due': str(due), 'source': '/claims/' + claim['id'].lower() + '/',
                       'kind': 'claim-review', 'evidential_status': claim['dimensions']['evidential_status']})
    for renewal in publications.get('review_dispositions', []):
        cid = renewal['claim_id']
        before = registry_at(renewal['before_revision'])[cid]
        after = registry_at(renewal['after_revision'])[cid]
        if date(after['last_reviewed']) <= date(before['last_reviewed']):
            raise ValueError(f'{cid}: recorded review did not advance')
        due = date(before['last_reviewed']) + dt.timedelta(days=int(before['review_window_days']))
        result.append({'id': cid + '@' + renewal['before_revision'][:7],
                       'title': cid + ' previous evidence review', 'due': str(due),
                       'source': 'https://github.com/Cubits11/cubits11.github.io/blob/' + renewal['before_revision'] + '/claims.yaml',
                       'kind': 'claim-review', 'disposition': {
                           'date': str(after['last_reviewed']),
                           'url': '/claims/' + cid.lower() + '/',
                           'summary': renewal['summary'] + ' Registry transition: ' + renewal['after_revision'][:7] + '.'}})
    for item in publications['deadlines']:
        date(item['due'])
        disposition = item.get('disposition')
        if disposition:
            date(disposition['date'])
            target = ROOT / disposition['url'].split('#')[0].strip('/') / 'index.html'
            if not target.exists():
                raise ValueError(f"{item['id']}: disposition target does not exist")
            anchor = disposition['url'].partition('#')[2]
            if anchor and f'id="{anchor}"' not in target.read_text():
                raise ValueError(f"{item['id']}: disposition anchor does not exist")
        result.append(dict(item, kind='publication-promise'))
    if len({item['id'] for item in result}) != len(result):
        raise ValueError('duplicate public deadline ID')
    return sorted(result, key=lambda item: (item['due'], item['id']))


def label(item, as_of):
    if item.get('disposition') and date(item['disposition']['date']) <= as_of:
        return 'DISPOSITION RECORDED'
    if as_of > date(item['due']):
        return 'OVERDUE — REVIEW REQUIRED' if item['kind'] == 'claim-review' else 'OVERDUE'
    return 'DUE TODAY' if as_of == date(item['due']) else 'SCHEDULED'


def deadline_list(items, as_of):
    rows = []
    for item in items:
        disposition = item.get('disposition')
        attrs = f'data-deadline="{item["due"]}" data-deadline-kind="{item["kind"]}"'
        if disposition:
            attrs += f' data-disposed-on="{disposition["date"]}"'
        content = (f'<span class="status-label" data-deadline-label>{label(item, as_of)}</span>'
                   f'<a href="{esc(item["source"])}">{esc(item["title"])}</a>'
                   f'<p>Due <time datetime="{item["due"]}">{item["due"]}</time>.</p>')
        if disposition:
            content += (f'<p><a href="{esc(disposition["url"])}">Disposition {disposition["date"]}</a>: '
                        f'{esc(disposition["summary"])}</p>')
        elif item['kind'] == 'claim-review':
            content += '<p>An elapsed review window requests review. It does not automatically refute the claim or change its evidential status.</p>'
        rows.append(f'<li {attrs}>{content}</li>')
    return '<ul class="status-list">' + ''.join(rows) + '</ul>'


def draft_board(drafts, observed_on):
    rows = []
    for item in drafts:
        revision = item['revision']
        if len(revision) != 40 or any(c not in '0123456789abcdef' for c in revision):
            raise ValueError('invalid draft revision')
        if revision not in item['result_url']:
            raise ValueError('draft result is not pinned to its declared revision')
        claim_link = ''
        if item.get('claim_url'):
            target = ROOT / item['claim_url'].strip('/') / 'index.html'
            if not item['claim_url'].startswith('/claims/') or not target.is_file():
                raise ValueError('draft claim must link to an existing registered claim')
            claim_link = f' · <a href="{esc(item["claim_url"])}">Inspect the registered claim and falsifier</a>'
        rows.append(f'''<article class="status-notice" data-draft-revision="{revision}" data-publication-state="{esc(item['status'])}"><p class="mono">{esc(item['status'])} · observed {observed_on}</p>
<h2>{esc(item['title'])}</h2><p>{esc(item['summary'])}</p><p>{esc(item['limitations'])}</p>
<p><a href="{esc(item['result_url'])}">Read the pinned result</a> · <a href="{esc(item['branch_url'])}">Inspect publication record</a>{claim_link}</p>
<p>Observed revision <code>{revision}</code>. This board is a dated observation, not a live claim that the repository is unchanged.</p></article>''')
    return '\n'.join(rows)


def build():
    claims = yaml.safe_load((ROOT / 'claims.yaml').read_text())
    publications = yaml.safe_load((ROOT / 'publications.yaml').read_text())
    observed_on = str(publications['observed_on'])
    as_of = date(observed_on)
    items = records(claims, publications)
    title = 'Checks, review dates and pending work'
    header = head(title, 'Live workflow results, registry-derived review dates, dated dispositions and scoped research results.', '/status/', 'website', [])
    header = header.replace('</head>', '<link rel="stylesheet" href="/assets/status.css">\n<script defer src="/assets/check-status.js"></script>\n<script defer src="/assets/deadlines.js"></script>\n</head>')
    status = BANNER + header + SITE_HEAD + f'''<main id="main" class="status-shell"><div class="container">
<h1>{title}</h1><p>Check outcomes and overdue reviews stay distinct from scientific truth.</p>
<div class="check-status" data-live-check role="status" aria-live="polite">Latest full check: UNKNOWN — checking GitHub.</div>
<p>GitHub is read when this page opens. A failed or unavailable request shows UNKNOWN. No workflow result establishes scientific validity.</p>
<p><a href="/status/preview/">Exercise the failed and unavailable preview states</a> · <a href="/records/conformance/">Inspect scientific check coverage</a> · <a href="/limits/">What receipts and checks establish</a></p>
<h2>Review queue</h2><p>Claim review dates are calculated from the registry's last review plus its review window. Recorded renewals retain the earlier deadline, calculated from the pinned registry revision. Other dated promises come from the publication list. Static snapshot: {observed_on}; JavaScript updates labels against today's date in New York.</p>
{deadline_list(items, as_of)}
<h2>Research pipeline</h2>{draft_board(publications['drafts'], observed_on)}
</div></main>''' + footer([('/now/', 'Research board'), ('/notes/noetic-log-002/#lookback-2026-10-17', 'Dated lookback'), ('/ledger/', 'Claim ledger'), ('/', 'Home')])
    preview_head = head('Workflow status preview', 'Synthetic failed and unavailable states for checking the public status component.', '/status/preview/', 'website', [])
    preview_head = preview_head.replace('</head>', '<link rel="stylesheet" href="/assets/status.css">\n<script defer src="/assets/check-status.js"></script>\n<script defer src="/assets/status-preview.js"></script>\n</head>')
    preview = BANNER + preview_head + SITE_HEAD + '''<main id="main" class="status-shell"><div class="container">
<h1>Workflow status preview</h1><p class="status-notice">Synthetic fixtures only. These buttons do not run CI or report the public repository's current health.</p>
<div class="status-fixture-controls"><button class="btn" id="preview-failed">Show failing check</button><button class="btn" id="preview-unavailable">Show unavailable check</button></div>
<div class="check-status" id="preview-status" role="status" aria-live="polite">Choose a synthetic state.</div>
</div></main>''' + footer([('/status/', 'Live status'), ('/', 'Home')])
    return {ROOT/'status/index.html': status, ROOT/'status/preview/index.html': preview,
            ROOT/'data/public-state.json': json.dumps({'observed_on':observed_on,'deadlines':items,'drafts':publications['drafts']}, indent=2) + '\n'}


def main():
    result = build()
    failed = False
    for path, content in result.items():
        content = '\n'.join(line.rstrip() for line in content.splitlines()) + '\n'
        if '--check' in sys.argv:
            if not path.exists() or path.read_text() != content:
                print('DRIFT ' + path.relative_to(ROOT).as_posix()); failed = True
        else:
            path.parent.mkdir(parents=True, exist_ok=True); path.write_text(content)
    # The draft board is generated in-place; the rest of /now/ remains editorial.
    now = ROOT/'now/index.html'
    html = now.read_text()
    opening, closing = '<!-- PUBLIC-DRAFT-BOARD:START -->', '<!-- PUBLIC-DRAFT-BOARD:END -->'
    if opening not in html or closing not in html:
        raise ValueError('/now/ has no generated draft-board slots')
    publications = yaml.safe_load((ROOT / 'publications.yaml').read_text())
    board = draft_board(publications['drafts'], str(publications['observed_on']))
    content = html.split(opening)[0] + opening + '\n' + board + '\n' + closing + html.split(closing)[1]
    if '--check' in sys.argv:
        if html != content: print('DRIFT now/index.html draft board'); failed = True
    else: now.write_text(content)
    print('public state: ' + ('drift' if failed else 'current'))
    return int(failed)


if __name__ == '__main__':
    raise SystemExit(main())
